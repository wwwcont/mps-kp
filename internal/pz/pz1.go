func tauStr(r, c string) string {
	rv := parseVal(r) * 1e3
	cv := parseVal(c) * 1e-6
	return Num(rv*cv*1e3, 0) + " мс"
}

// parseVal — «10 к» → 10, «10 мк» → 10.
func parseVal(s string) float64 {
	var v float64
	fmt.Sscanf(strings.ReplaceAll(s, ",", "."), "%g", &v)
	return v
}

