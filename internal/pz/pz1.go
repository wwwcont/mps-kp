// BOMLine — строка перечня из sheet.json (schgen.BOMLine).
type BOMLine struct {
	Refs, Name, Note, Group string
	Qty                     int
}

// PZ1 — вход для ПЗ1.
type PZ1 struct {
	P         *variant.Params
	GroupFull string
	Checker   string
	Year      int
	Date      string
	Refs      map[string][2]string // роль → (позиционное обозначение, номинал/тип)
	BOM       []BOMLine
	Figs      map[string]string // узел → файл PNG в Dir: struct, func, mcu, dec, idt, kb, ind, y2, power, tread, twrite, sheet
	FigW      map[string]float64
}

func (in PZ1) ref(role string) string { return in.Refs[role][0] }

// refsOf — обозначения всех элементов с ролью prefix0, prefix1, … одной строкой («R2–R5»).
func (in PZ1) refsOf(prefix string) string {
	type r struct {
		p string
		n int
	}
	var rs []r
	for role, v := range in.Refs {
		if strings.HasPrefix(role, prefix) && len(role) > len(prefix) && role[len(prefix)] >= '0' && role[len(prefix)] <= '9' {
			var n int
			pre := strings.TrimRight(v[0], "0123456789")
			fmt.Sscanf(v[0][len(pre):], "%d", &n)
			rs = append(rs, r{pre, n})
		}
	}
	if len(rs) == 0 {
		return "?"
	}
	sort.Slice(rs, func(i, j int) bool { return rs[i].n < rs[j].n })
	if len(rs) == 1 {
		return fmt.Sprintf("%s%d", rs[0].p, rs[0].n)
	}
	sep := "–"
	if len(rs) == 2 {
		sep = ", " + rs[1].p
		return fmt.Sprintf("%s%d%s%d", rs[0].p, rs[0].n, sep, rs[1].n)
	}
	return fmt.Sprintf("%s%d%s%s%d", rs[0].p, rs[0].n, sep, rs[len(rs)-1].p, rs[len(rs)-1].n)
}
func (in PZ1) val(role string) string { return in.Refs[role][1] }

// bomValue — номинал из перечня по первому элементу с префиксом и частью наименования («МЛТ» + «2 кОм»).
func (in PZ1) bomFind(prefix, contains string) (refs, name string) {
	for _, l := range in.BOM {
		if strings.HasPrefix(l.Refs, prefix) && strings.Contains(l.Name, contains) {
			return l.Refs, l.Name
		}
	}
	return "", ""
}

// e24 — ближайший номинал ряда E24 не меньше v (для проверки выбора).
func e24Up(v float64) float64 {
	base := []float64{1.0, 1.1, 1.2, 1.3, 1.5, 1.6, 1.8, 2.0, 2.2, 2.4, 2.7, 3.0, 3.3, 3.6, 3.9, 4.3, 4.7, 5.1, 5.6, 6.2, 6.8, 7.5, 8.2, 9.1}
	dec := math.Pow(10, math.Floor(math.Log10(v)))
	for _, b := range base {
		if b*dec >= v-1e-9 {
			return b * dec
		}
	}
	return 10 * dec
}

