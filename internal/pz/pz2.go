// expandTabs — табуляции до позиций, кратных 8 (как в редакторе): комментарии встают в столбец.
func expandTabs(s string) string {
	var b strings.Builder
	col := 0
	for _, r := range s {
		switch r {
		case '\t':
			n := 8 - col%8
			b.WriteString(strings.Repeat(" ", n))
			col += n
		case '\n':
			b.WriteRune(r)
			col = 0
		case '\r':
		default:
			b.WriteRune(r)
			col++
		}
	}
	return b.String()
}

func dash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return s
}

// dataVars — переменные из DSEG программ студента.
func dataVars(in PZ2) [][]string {
	type v struct {
		name string
		addr int
		prog []string
	}
	m := map[string]*v{}
	for _, pr := range in.Programs {
		res := asm51.Assemble("p.a51", pr.Src, func(string) (string, error) { return in.VarsInc, nil })
		for _, s := range res.Symbols {
			if s.Kind != "DATA" || s.Line < 0 || res.Lines[s.Line].Included {
				continue
			}
			key := strings.ToUpper(s.Name)
			if m[key] == nil {
				m[key] = &v{name: s.Name, addr: s.Value}
			}
			m[key].prog = append(m[key].prog, fmt.Sprint(pr.N))
		}
	}
	var out [][]string
	var keys []string
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return m[keys[i]].addr < m[keys[j]].addr })
	for _, k := range keys {
		x := m[k]
		desc := "переменная программы " + strings.Join(x.prog, ", ")
		switch k {
		case "X1":
			desc = "сигнал *X*~1~ — цифра с клавиатуры"
		case "X2":
			desc = "сигнал *X*~2~ — отсчёт из буфера"
		}
		out = append(out, []string{esc(x.name), hx(x.addr), desc})
	}
	return out
}

// plural — 1 байт, 2 байта, 5 байт.
func plural(n int, one, few, many string) string {
	switch {
	case n%10 == 1 && n%100 != 11:
		return one
	case n%10 >= 2 && n%10 <= 4 && (n%100 < 12 || n%100 > 14):
		return few
	}
	return many
}
