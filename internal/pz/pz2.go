// segment-коды символов (общий катод, D0…D7 = a…g, dp)
var segCodes = []struct {
	sym  string
	code byte
}{{"0", 0x3F}, {"1", 0x06}, {"2", 0x5B}, {"3", 0x4F}, {"4", 0x66}, {"5", 0x6D}, {"6", 0x7D}, {"7", 0x07}, {"8", 0x7F}, {"9", 0x6F}, {"E", 0x79}}

func hx(v int) string {
	s := fmt.Sprintf("%02X", v)
	if v > 0xFF {
		s = fmt.Sprintf("%04X", v)
	}
	if s[0] >= 'A' {
		s = "0" + s
	}
	return s + "h"
}

func prog3Kind(p *variant.Params) int { return p.M % 3 }

